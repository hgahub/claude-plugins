"""Builds the knowledge base's note map: map/<app>.md, one row per note, with its related notes.

Usage: python build_map.py [<knowledge-dir>]   (default: the configured knowledge base)

Notes live in notes/ and are named `<app>-<issue>-<topic>.md` (or `<app>-<topic>.md` without an issue). The
app is the longest apps/<app>.md name the file name starts with; without a match, the part before the issue
number, or else the first word. For every app with notes, map/<app>.md lists each note with its title,
`verified_at`, `status`, issue numbers (from the file name and `#NNN` in the title) and related notes:
wikilinks in both directions, and `#NNN` mentions of the same app's issues in both directions.
Map pages carry a marker; ones whose app no longer has notes are removed. Do not edit them by hand.
Only notes/ is read: the metrics records (metrics/**/*.json) are not notes and are not on the map.

Exit code: 0 done, 2 wrong usage.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from kb_common import default_root, issue_refs, split_frontmatter, wikilinks  # noqa: E402

MARKER = "<!-- generated by build_map.py; do not edit -->"
NUMBERED_RE = re.compile(r"^(?P<app>.+?)-(?P<num>\d{1,6})(?:-|$)")


def app_of(stem: str, apps: list[str]) -> tuple[str, int | None]:
    """The note's app and issue number, from its file name."""
    for app in sorted(apps, key=len, reverse=True):
        if stem == app or stem.startswith(f"{app}-"):
            rest = stem[len(app) + 1 :]
            m = re.match(r"^(\d{1,6})(?:-|$)", rest)
            return app, int(m.group(1)) if m else None
    m = NUMBERED_RE.match(stem)
    if m:
        return m.group("app"), int(m.group("num"))
    return stem.split("-", 1)[0], None


def cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ").strip()


def build(root: Path) -> dict[str, str]:
    """Returns {map file name: content} for every app that has notes."""
    apps = [p.stem for p in (root / "apps").glob("*.md") if p.name.lower() != "readme.md"] if (root / "apps").is_dir() else []
    notes_dir = root / "notes"
    notes = []
    for p in sorted(notes_dir.glob("*.md")) if notes_dir.is_dir() else []:
        if p.name.lower() == "readme.md":
            continue
        text = p.read_text(encoding="utf-8")
        fields, body, _first = split_frontmatter(text)
        fields = fields or {}
        app, num = app_of(p.stem, apps)
        title = fields.get("title") or p.stem
        issues = {num} if num is not None else set()
        issues |= issue_refs(title)
        notes.append({
            "stem": p.stem, "app": app, "title": title, "issues": issues,
            "verified_at": fields.get("verified_at", "—"), "status": fields.get("status", "—"),
            "links": set(wikilinks(body)), "mentions": issue_refs(body),
        })

    by_stem = {n["stem"]: n for n in notes}
    related: dict[str, set[str]] = defaultdict(set)
    for n in notes:
        for target in n["links"]:
            if target in by_stem and target != n["stem"]:
                related[n["stem"]].add(target)
                related[target].add(n["stem"])
        for other in notes:
            if other is n or other["app"] != n["app"]:
                continue
            if n["mentions"] & other["issues"]:
                related[n["stem"]].add(other["stem"])
                related[other["stem"]].add(n["stem"])

    out: dict[str, str] = {}
    for app in sorted({n["app"] for n in notes}):
        rows = sorted((n for n in notes if n["app"] == app), key=lambda n: (min(n["issues"]) if n["issues"] else 10**7, n["stem"]))
        lines = [
            MARKER,
            f"# Note map: {app}",
            "",
            f"{len(rows)} note(s). Generated from `notes/`; rebuild with `build_map.py`.",
            "",
            "| Note | Verified | Status | Issues | Related |",
            "|---|---|---|---|---|",
        ]
        for n in rows:
            issues = ", ".join(f"#{i}" for i in sorted(n["issues"])) or "—"
            rel = ", ".join(f"[[{s}]]" for s in sorted(related[n["stem"]])) or "—"
            lines.append(f"| [[{n['stem']}]] {cell(n['title'])} | {n['verified_at']} | {n['status']} | {issues} | {rel} |")
        out[f"{app}.md"] = "\n".join(lines) + "\n"
    return out


def main(argv: list[str] | None = None) -> int:
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("root", nargs="?", default=default_root())
    a = ap.parse_args(argv)
    root = Path(a.root).expanduser()
    if not root.is_dir():
        print(f"not a directory: {root}", file=sys.stderr)
        return 2
    maps = build(root)
    map_dir = root / "map"
    map_dir.mkdir(exist_ok=True)
    changed = []
    for name, content in maps.items():
        path = map_dir / name
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            with open(path, "w", encoding="utf-8", newline="\n") as fh:  # write_text(newline=) needs Python 3.10
                fh.write(content)
            changed.append(f"map/{name}")
    for path in map_dir.glob("*.md"):
        if path.name not in maps and path.read_text(encoding="utf-8").startswith(MARKER):
            path.unlink()
            changed.append(f"map/{path.name} (removed)")
    print(f"{len(maps)} map page(s); changed: {', '.join(changed) if changed else 'none'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
